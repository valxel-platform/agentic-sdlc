"""The single-VM tier (ADR 0007, T-69): `valxel vm init|doctor|up|down|backup|restore|upgrade`.

`init` lays out the bundle (bundle/compose.yaml) and generates the secrets the tool makes itself;
the ones only the operator has (the model key, the GitHub App's keys, the OAuth client secret) are
files to fill in, and `doctor` names what's missing. Every image is pinned by digest; `upgrade`
moves the tool to a new digest after checking its signature and taking a backup, and goes back if
the new version doesn't come up healthy.
"""

from __future__ import annotations

import os
import re
import secrets
import shutil
import stat
import subprocess
import sys
import time
from pathlib import Path

BUNDLE_FILES = ("compose.yaml", "Caddyfile", "backup.sh", "initdb/10-roles.sh", "gateway-policy.yaml", "README.md")
IMAGES = ("VALXEL_IMAGE", "GATEWAY_IMAGE", "AUDIT_SINK_IMAGE", "POSTGRES_IMAGE", "KAFKA_IMAGE", "CADDY_IMAGE")
DIGEST = re.compile(r"^[\w./:-]+@sha256:[0-9a-f]{64}$")
# Generated by init; never shown again.
GENERATED = ("VALXEL_SESSION_SECRET", "VALXEL_GITHUB_WEBHOOK_SECRET", "VALXEL_LLM_GATEWAY_API_KEY",
             "POSTGRES_SUPERUSER_PASSWORD", "VALXEL_DB_PASSWORD", "AUDIT_DB_PASSWORD", "session-launcher-token",
             "VALXEL_GIT_BROKER_KEY")
# Only the operator has these: init leaves them empty for doctor to name.
OPERATOR = {
    "VALXEL_GITHUB_APP_PRIVATE_KEY": "the Delivery GitHub App's private key (PEM)",
    "VALXEL_GITHUB_PROVISIONER_PRIVATE_KEY": "the Provisioning GitHub App's private key (PEM)",
    "VALXEL_GITHUB_OAUTH_CLIENT_SECRET": "the GitHub OAuth App's client secret, for sign-in",
}
SIGNER = r"^https://github\.com/valxel-platform/agentic-sdlc/\.github/workflows/.+@refs/(heads/main|tags/v.+)$"


def home() -> Path:
    return Path(os.environ.get("VALXEL_VM_HOME") or "/opt/valxel")


def bundle() -> Path:
    return Path(__file__).resolve().parent / "bundle"


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                out[k.strip()] = v.strip()
    return out


def write_env(path: Path, values: dict[str, str]) -> None:
    path.write_text("".join(f"{k}={v}\n" for k, v in values.items()))
    path.chmod(stat.S_IRUSR | stat.S_IWUSR)


def _secret_file(d: Path, name: str, value: str) -> None:
    """Readable by the containers' users (Compose bind-mounts each file); the folder is the owner's only."""
    f = d / name
    f.write_text(value)
    f.chmod(0o644)


def docker_gid(sock: str = "/var/run/docker.sock") -> str:
    try:
        return str(os.stat(sock).st_gid)
    except OSError:
        return ""


def init(*, target: Path | None = None, domain: str, email: str, force: bool = False) -> Path:
    """Lay out the bundle and generate its secrets. Re-running keeps every secret already there."""
    from ..laptop import gateway_policy

    target = target or home()
    target.mkdir(parents=True, exist_ok=True)
    target.chmod(0o700)
    for rel in BUNDLE_FILES:
        dst = target / rel
        if dst.exists() and not force and rel not in ("compose.yaml", "backup.sh", "Caddyfile"):
            continue
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(bundle() / rel, dst)
    (target / "initdb" / "10-roles.sh").chmod(0o755)
    sec = target / "secrets"
    sec.mkdir(exist_ok=True)
    sec.chmod(0o700)
    for name in GENERATED:
        if not (sec / name).exists() or not (sec / name).read_text().strip():
            prefix = {"VALXEL_LLM_GATEWAY_API_KEY": "vxg_", "session-launcher-token": "vxl_"}.get(name, "")
            # The git broker's key is 32 bytes in hex (valxel_sdlc.git_broker).
            value = secrets.token_hex(32) if name == "VALXEL_GIT_BROKER_KEY" else prefix + secrets.token_urlsafe(32)
            _secret_file(sec, name, value)
    db_pw = (sec / "VALXEL_DB_PASSWORD").read_text().strip()
    audit_pw = (sec / "AUDIT_DB_PASSWORD").read_text().strip()
    _secret_file(sec, "DATABASE_URL", f"postgresql://valxel:{db_pw}@postgres:5432/valxel")
    for name in OPERATOR:
        if not (sec / name).exists():
            _secret_file(sec, name, "")
    if not (sec / "gateway.env").exists():
        (sec / "gateway.env").write_text("ANTHROPIC_API_KEY=\n")
    (sec / "gateway.env").chmod(0o600)
    (sec / "audit-sink.env").write_text(
        f"AUDIT_SINK_DATABASE_URL=postgresql://audit:{audit_pw}@postgres:5432/audit\n"
        'AUDIT_SINK_DESTINATIONS=["postgres"]\n')
    (sec / "audit-sink.env").chmod(0o600)
    gw_key = (sec / "VALXEL_LLM_GATEWAY_API_KEY").read_text().strip()
    policy = target / "gateway-policy.local.yaml"
    policy.write_text(gateway_policy(gw_key))
    policy.chmod(0o644)
    env = read_env(target / ".env")
    env.update({"VALXEL_DOMAIN": domain or env.get("VALXEL_DOMAIN", ""),
                "ACME_EMAIL": email or env.get("ACME_EMAIL", ""), "DOCKER_GID": docker_gid() or env.get("DOCKER_GID", "")})
    for k in IMAGES + ("VALXEL_GITHUB_APP_ID", "VALXEL_GITHUB_PROVISIONER_APP_ID", "VALXEL_GITHUB_OAUTH_CLIENT_ID"):
        env.setdefault(k, "")
    write_env(target / ".env", env)
    return target


def _run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, check=False, **kw)


def compose(target: Path, *args: str) -> list[str]:
    return ["docker", "compose", "-p", "valxel", "-f", str(target / "compose.yaml"),
            "--env-file", str(target / ".env"), *args]


def last_backup(target: Path, *, run=_run) -> str:
    r = run(compose(target, "exec", "-T", "backup", "cat", "/backups/last-success"))
    return r.stdout.strip() if r.returncode == 0 else ""


def doctor(target: Path | None = None, *, run=_run, now: float | None = None) -> list[tuple[str, bool, str]]:
    """Each check: (what, ok, how to fix)."""
    target = target or home()
    checks: list[tuple[str, bool, str]] = []
    have_docker = shutil.which("docker") is not None
    checks.append(("Docker", have_docker, "Install Docker Engine"))
    if have_docker:
        info = run(["docker", "info", "--format", "{{json .Runtimes}}"])
        checks.append(("Docker running", info.returncode == 0, "Start Docker"))
        checks.append(("gVisor (runsc) in Docker", '"runsc"' in info.stdout,
                       ("Install gVisor and register it: `runsc install && systemctl restart docker` "
                        "(https://gvisor.dev/docs/user_guide/install/)")))
        comp = run(["docker", "compose", "version", "--short"])
        checks.append(("Docker Compose v2", comp.returncode == 0, "Install the Compose plugin"))
    env = read_env(target / ".env")
    checks.append(("Initialised", (target / ".env").exists(), "Run: valxel vm init --domain <name> --email <you>"))
    checks.append(("Domain", bool(env.get("VALXEL_DOMAIN")), "valxel vm init --domain <name>; point its DNS at this VM"))
    checks.append(("Let's Encrypt email", bool(env.get("ACME_EMAIL")), "valxel vm init --email <you>"))
    for k in IMAGES:
        checks.append((f"{k} pinned by digest", bool(DIGEST.match(env.get(k, ""))),
                       f"Set {k}=<image>@sha256:<digest> in .env (the tool's: valxel vm upgrade)"))
    sec = target / "secrets"
    for name, what in OPERATOR.items():
        f = sec / name
        checks.append((f"secret {name}", f.exists() and bool(f.read_text().strip()), f"Write {what} to {f}"))
    gw = read_env(sec / "gateway.env")
    checks.append(("Model key for the gateway", bool(gw.get("ANTHROPIC_API_KEY")),
                   f"Set ANTHROPIC_API_KEY in {sec / 'gateway.env'}"))
    for k in ("VALXEL_GITHUB_APP_ID", "VALXEL_GITHUB_PROVISIONER_APP_ID", "VALXEL_GITHUB_OAUTH_CLIENT_ID"):
        checks.append((k, bool(env.get(k)), f"Set {k} in .env"))
    if have_docker and run(compose(target, "ps", "-q", "backup")).stdout.strip():
        last = last_backup(target, run=run)
        fresh = False
        if last:
            from datetime import UTC, datetime

            at = datetime.strptime(last, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=UTC).timestamp()
            fresh = (now or time.time()) - at < 26 * 3600
        checks.append(("Backup in the last 26 hours", fresh, "Check: docker compose logs backup; run valxel vm backup"))
    return checks


def verify(ref: str, *, run=_run) -> tuple[bool, str]:
    """The image's cosign signature, from the tool's own release workflow (keyless, GitHub OIDC)."""
    if not shutil.which("cosign"):
        return False, "cosign isn't installed: install it, or pass --no-verify knowingly"
    r = run(["cosign", "verify", ref, "--certificate-identity-regexp", SIGNER,
             "--certificate-oidc-issuer", "https://token.actions.githubusercontent.com"])
    return r.returncode == 0, (r.stderr or r.stdout).strip()[-300:]


def healthy(target: Path, *, run=_run, wait_s: float = 300, sleep=time.sleep, clock=time.monotonic) -> bool:
    deadline = clock() + wait_s
    while clock() < deadline:
        r = run(["docker", "inspect", "--format", "{{.State.Health.Status}}",
                 run(compose(target, "ps", "-q", "api")).stdout.strip() or "none"])
        if r.stdout.strip() == "healthy":
            return True
        sleep(5)
    return False


def upgrade(target: Path, ref: str, *, no_verify: bool = False, run=_run, sleep=time.sleep,
            clock=time.monotonic) -> str:
    """Move the tool to `ref` (by digest): check its signature, back up, switch, wait until it's
    healthy, and go back to the previous digest if it isn't."""
    if not DIGEST.match(ref):
        raise ValueError("Upgrade to an image by digest: <image>@sha256:<64 hex>")
    if not no_verify:
        ok, why = verify(ref, run=run)
        if not ok:
            raise ValueError(f"{ref}'s signature didn't verify: {why}")
    env = read_env(target / ".env")
    previous = env.get("VALXEL_IMAGE", "")
    if run(compose(target, "ps", "-q", "backup")).stdout.strip():
        b = run(compose(target, "exec", "-T", "backup", "sh", "/backup.sh", "once"))
        if b.returncode != 0:
            raise RuntimeError(f"The backup before the upgrade failed: {b.stderr.strip()[-300:]}")
    env.update({"VALXEL_IMAGE": ref, "VALXEL_IMAGE_PREVIOUS": previous})
    write_env(target / ".env", env)
    run(compose(target, "pull", "api", "worker", "provisioner", "session-launcher", "egress-proxy"))
    run(compose(target, "up", "-d"))
    if healthy(target, run=run, sleep=sleep, clock=clock):
        return f"Upgraded to {ref}"
    if not previous:
        return f"{ref} isn't healthy, and there's no previous version to go back to"
    env.update({"VALXEL_IMAGE": previous, "VALXEL_IMAGE_PREVIOUS": ref})
    write_env(target / ".env", env)
    run(compose(target, "up", "-d"))
    return f"{ref} wasn't healthy in time: went back to {previous}"


def restore(target: Path, folder: str, *, run=_run) -> None:
    """Restore a night's backup (its folder name, e.g. 20261121T023000Z): the tool stops meanwhile."""
    if not re.fullmatch(r"\d{8}T\d{6}Z", folder):
        raise ValueError("Name the backup by its folder, e.g. 20261121T023000Z")
    run(compose(target, "stop", "api", "worker", "provisioner", "audit-sink"))
    for db in ("valxel", "audit"):
        r = run(compose(target, "exec", "-T", "backup", "sh", "-c",
                        f'PGPASSWORD="$(cat $PGPASSWORD_FILE)" pg_restore --clean --if-exists -d {db} '
                        f"/backups/{folder}/{db}.dump"))
        if r.returncode != 0:
            raise RuntimeError(f"Restoring {db} failed: {r.stderr.strip()[-300:]}")
    run(compose(target, "run", "--rm", "--no-deps", "-v", "valxel_backups:/backups:ro", "--entrypoint", "sh",
                "worker", "-c", f"rm -rf /data/artifacts/* && tar -C /data -xzf /backups/{folder}/artifacts.tgz"))
    run(compose(target, "start", "api", "worker", "provisioner", "audit-sink"))


def add_parser(sub) -> None:
    vm = sub.add_parser("vm", help="The single-VM tier: the tool hardened on one VM (init, doctor, up, down, backup, "
                                   "restore, upgrade)")
    vm.add_argument("action", choices=["init", "doctor", "up", "down", "backup", "restore", "upgrade"])
    vm.add_argument("value", nargs="?", help="restore: the backup's folder; upgrade: the image by digest")
    vm.add_argument("--home", help="Where the bundle lives (default /opt/valxel)")
    vm.add_argument("--domain", default="", help="init: the tool's domain (its DNS points at this VM)")
    vm.add_argument("--email", default="", help="init: the email Let's Encrypt writes to about the certificate")
    vm.add_argument("--force", action="store_true", help="init: overwrite the policy template and README")
    vm.add_argument("--no-verify", action="store_true", help="upgrade: skip the signature check (not advised)")


def main(args) -> int:
    target = Path(args.home) if getattr(args, "home", None) else home()
    if args.action == "init":
        init(target=target, domain=args.domain, email=args.email, force=args.force)
        print(f"Ready in {target}. Next: fill in what `valxel vm doctor` names, then `valxel vm up`.")
        return 0
    if args.action == "doctor":
        checks = doctor(target)
        for what, ok, fix in checks:
            print(f"{'ok ' if ok else 'NO '} {what}" + ("" if ok else f"  -> {fix}"))
        return 0 if all(ok for _, ok, _ in checks) else 1
    if args.action == "up":
        bad = [w for w, ok, _ in doctor(target) if not ok and not w.startswith("Backup")]
        if bad:
            print("Not starting: " + "; ".join(bad) + " (valxel vm doctor)", file=sys.stderr)
            return 1
        return subprocess.call(compose(target, "up", "-d"))
    if args.action == "down":
        return subprocess.call(compose(target, "down"))
    if args.action == "backup":
        return subprocess.call(compose(target, "exec", "-T", "backup", "sh", "/backup.sh", "once"))
    if args.action == "restore":
        restore(target, args.value or "")
        print(f"Restored {args.value}.")
        return 0
    if args.action == "upgrade":
        print(upgrade(target, args.value or "", no_verify=args.no_verify))
        return 0
    return 2

